# in python there are many types of opr.
"""
1. addition +
2. subtraction -
3. multiplication *
4. modulus %
5. floor division //
6. division /
7. exponentiation **
"""
num1 = int(input("Enter the num 1:\n"))
num2 = int(input("Enter the num 2:\n"))

addition = num1+num2
subtraction = num1-num2
multiplication = num1*num2

# gives the remainder 
modulus = num1%num2

# gives the floor version
floor_division = num1//num2

# gives the complete division
division = num1/num2

# gives (firstxsecond number times)
exponentiation = num1**num2
print(addition)
print(subtraction)
print(modulus)
print(floor_division)
print(division)
print(exponentiation)
print(multiplication)
